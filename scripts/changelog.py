#!/usr/bin/env python3
"""The changelog: one file per released version, written from per-PR fragments.

    changelogs/<version>.md          one released version, headed "## [X.Y.Z] - YYYY-MM-DD"
    changelogs/unreleased/<name>.md  one pull request's entries, waiting for a release
    changelogs/README.md             the versioning scheme and the index (generated)

A pull request that changes something a release publishes writes its notes to a
fragment of its own, named after its branch with "/" turned into "-"
(quotes/add-stoics -> changelogs/unreleased/quotes-add-stoics.md). Pull requests
then never edit the same file. A fragment is one or more "### Section" headers
(SECTIONS below), each followed by free Markdown — prose, lists, wrapped lines —
and nothing outside a section:

    ### Added
    Three quotes added to **Daily Inspiration**: ...

The release PR runs `release`, which writes changelogs/<version>.md from every
fragment (each section's bodies in fragment file-name order, the sections in
SECTIONS order), deletes the fragments and rewrites the index. The tag's workflow
reads the notes back with `notes`, and refuses to publish a version that has none.

Usage:
    changelog.py [--root ROOT] check               # CI: fragments, version files, index
    changelog.py [--root ROOT] preview             # the next release's notes, from the fragments
    changelog.py [--root ROOT] release VERSION [--date YYYY-MM-DD] [--extend]
    changelog.py [--root ROOT] notes VERSION       # a version's notes, without its heading
    changelog.py [--root ROOT] index               # rewrite changelogs/README.md

Stdlib only. Exit code 0 on success, 1 on failure.
"""

import argparse
import datetime
import os
import re
import sys

SECTIONS = ("Added", "Changed", "Removed", "Fixed", "Audited", "Notes")
VERSION = re.compile(r"^\d+\.\d+\.\d+$")
HEADING = re.compile(r"^## \[(\d+\.\d+\.\d+)\] - (\d{4}-\d{2}-\d{2})$")

README_HEADER = """# Changelog

All notable changes to the Quips collections data, one file per released version.

Versioning is semantic and scoped to the data:
- **patch** (`x.y.Z`) — quotes added to or edited within existing collections.
- **minor** (`x.Y.0`) — one or more new collections.
- **major** (`X.0.0`) — a breaking change to the data shape or schema.

Each released version is tagged `vX.Y.Z`; pushing the tag builds `dist/`, publishes
the GitHub Release, and uploads to `data.quipsapp.com`. A version's file, less its
heading, is used verbatim as that release's notes, and a tag with no file is refused.

## How it works

- **`unreleased/<branch-name>.md`** — each pull request that changes something a
  release publishes writes its notes here, in a fragment of its own (the branch name
  with `/` turned into `-`). The format is in `scripts/changelog.py`.
- **`<version>.md`** — written by `python3 scripts/changelog.py release <version>` in
  the release PR, from the fragments, which it deletes. Not edited by hand after that.
- **This file** — the scheme above and the index below; the index is generated by
  `python3 scripts/changelog.py index`.

## Versions
"""


class ChangelogError(Exception):
    pass


def _dir(root):
    return os.path.join(root, "changelogs")


def fragment_paths(root):
    folder = os.path.join(_dir(root), "unreleased")
    if not os.path.isdir(folder):
        return []
    return sorted(
        os.path.join(folder, name)
        for name in os.listdir(folder)
        if name.endswith(".md") and name != "README.md"
    )


def version_paths(root):
    """The version files, newest version first."""
    found = []
    for name in os.listdir(_dir(root)):
        stem = name[:-3] if name.endswith(".md") else None
        if stem and VERSION.match(stem):
            found.append((tuple(int(part) for part in stem.split(".")), os.path.join(_dir(root), name)))
    return [path for _, path in sorted(found, reverse=True)]


def parse_sections(text, name, allow_intro=False):
    """The file's sections, in order, each its body with surrounding blank lines removed.

    A version file may open with a paragraph before its first section (the backfilled
    notes say why they were written late); a fragment may not, since nothing would
    say which section its text belongs to.
    """
    sections = []
    for number, line in enumerate(text.splitlines(), 1):
        if line.startswith("### "):
            title = line[4:].strip()
            if title not in SECTIONS:
                raise ChangelogError(f"{name}:{number}: unknown section '### {title}'; use one of {', '.join(SECTIONS)}")
            sections.append((title, []))
        elif line.startswith("## ") or line.startswith("# "):
            raise ChangelogError(f"{name}:{number}: unexpected heading '{line}'")
        elif sections:
            sections[-1][1].append(line)
        elif line.strip() and not allow_intro:
            raise ChangelogError(f"{name}:{number}: text outside any '### Section' header")
    return [(title, "\n".join(body).strip("\n")) for title, body in sections]


def read_fragments(root):
    fragments = []
    for path in fragment_paths(root):
        name = os.path.relpath(path, root)
        with open(path, encoding="utf-8") as handle:
            sections = parse_sections(handle.read(), name)
        if not any(body.strip() for _, body in sections):
            raise ChangelogError(f"{name}: no entries")
        fragments.append(sections)
    return fragments


def fold(fragments):
    """The fragments' sections merged: SECTIONS order, bodies in fragment order."""
    bodies = {title: [] for title in SECTIONS}
    for sections in fragments:
        for title, body in sections:
            if body.strip():
                bodies[title].append(body)
    blocks = [f"### {title}\n" + "\n\n".join(bodies[title]) for title in SECTIONS if bodies[title]]
    return "\n\n".join(blocks) + "\n" if blocks else ""


def _extended(body, fragments):
    """`body` (a version file less its heading) with the fragments' bodies added."""
    lines = body.split("\n")
    first = next((i for i, line in enumerate(lines) if line.startswith("### ")), len(lines))
    intro = "\n".join(lines[:first]).strip("\n")
    sections = parse_sections("\n".join(lines[first:]), "version file")
    merged = {title: [text] if text.strip() else [] for title, text in sections}
    order = [title for title, _ in sections]
    for fragment in fragments:
        for title, text in fragment:
            if not text.strip():
                continue
            if title not in merged:
                merged[title] = []
                order.append(title)
            merged[title].append(text)
    blocks = [f"### {title}\n" + "\n\n".join(merged[title]) for title in order if merged[title]]
    return "\n\n".join(([intro] if intro else []) + blocks) + "\n"


def read_version(path, root):
    """(version, date, body) of a version file, checked against its file name."""
    name = os.path.relpath(path, root)
    with open(path, encoding="utf-8") as handle:
        lines = handle.read().split("\n")
    match = HEADING.match(lines[0]) if lines else None
    stem = os.path.basename(path)[:-3]
    if not match or match.group(1) != stem:
        raise ChangelogError(f"{name}:1: must start with '## [{stem}] - YYYY-MM-DD'")
    body = "\n".join(lines[1:]).strip("\n")
    parse_sections(body, name, allow_intro=True)
    return match.group(1), match.group(2), body


def render_index(root):
    lines = [README_HEADER]
    count = len(fragment_paths(root))
    if count:
        lines.append(f"- Unreleased: {count} fragment{'' if count == 1 else 's'} in [`unreleased/`](unreleased/)")
    for path in version_paths(root):
        version, date, _ = read_version(path, root)
        lines.append(f"- [{version}]({version}.md) — {date}")
    return "\n".join(lines) + "\n"


def index_path(root):
    return os.path.join(_dir(root), "README.md")


def write_index(root):
    with open(index_path(root), "w", encoding="utf-8") as handle:
        handle.write(render_index(root))


def check(root):
    read_fragments(root)
    for path in version_paths(root):
        read_version(path, root)
    current = ""
    if os.path.exists(index_path(root)):
        with open(index_path(root), encoding="utf-8") as handle:
            current = handle.read()
    if current != render_index(root):
        raise ChangelogError("changelogs/README.md is out of date: run `python3 scripts/changelog.py index`")


def release(root, version, date, extend=False):
    """Write changelogs/<version>.md from the fragments, delete them and rewrite the index.

    With `extend`, the version file already exists (an open release PR whose data has
    moved on): each fragment body joins the end of its section, a section the file
    lacks is added after the rest, any text a reviewer edited stays, and the heading
    takes `date`.
    """
    if not VERSION.match(version):
        raise ChangelogError(f"'{version}' is not X.Y.Z")
    target = os.path.join(_dir(root), f"{version}.md")
    if os.path.exists(target) and not extend:
        raise ChangelogError(f"changelogs/{version}.md already exists; pass --extend to add to it")
    if extend and not os.path.exists(target):
        raise ChangelogError(f"changelogs/{version}.md does not exist to extend")
    fragments = read_fragments(root)
    if not fold(fragments):
        raise ChangelogError("no fragments in changelogs/unreleased/ to release")
    if extend:
        _, _, body = read_version(target, root)
        notes = _extended(body, fragments)
    else:
        notes = fold(fragments)
    with open(target, "w", encoding="utf-8") as handle:
        handle.write(f"## [{version}] - {date}\n{notes}")
    removed = fragment_paths(root)
    for path in removed:
        os.remove(path)
    write_index(root)
    return target, len(removed)


def notes(root, version):
    path = os.path.join(_dir(root), f"{version}.md")
    if not os.path.exists(path):
        raise ChangelogError(f"changelogs/{version}.md not found: the release PR writes it with `changelog.py release {version}`")
    _, _, body = read_version(path, root)
    if not body.strip():
        raise ChangelogError(f"changelogs/{version}.md has no notes")
    return body + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", default=".", help="repo root (default: .)")
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("check")
    commands.add_parser("preview")
    commands.add_parser("index")
    cut = commands.add_parser("release")
    cut.add_argument("version")
    cut.add_argument("--date", default=datetime.date.today().isoformat())
    cut.add_argument("--extend", action="store_true", help="add the fragments to an existing version file")
    show = commands.add_parser("notes")
    show.add_argument("version")
    args = parser.parse_args(argv)

    try:
        if args.command == "check":
            check(args.root)
            count = len(fragment_paths(args.root))
            print(f"changelog OK: {len(version_paths(args.root))} versions, {count} fragment{'' if count == 1 else 's'}")
        elif args.command == "preview":
            sys.stdout.write(fold(read_fragments(args.root)) or "(no fragments)\n")
        elif args.command == "index":
            write_index(args.root)
            print("wrote changelogs/README.md")
        elif args.command == "release":
            target, count = release(args.root, args.version, args.date, args.extend)
            print(f"wrote {os.path.relpath(target, args.root)} from {count} fragment{'' if count == 1 else 's'}")
        elif args.command == "notes":
            sys.stdout.write(notes(args.root, args.version))
    except ChangelogError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
